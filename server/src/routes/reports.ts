import { Router, Request, Response } from 'express';
import { getDatabase } from '../db/database.js';
import { requireAuth } from '../middleware/auth.js';

export const reportsRouter = Router();

// Helper to format consistent report ID e.g. SGR-2026-XXXX
function generateReportId(scanId: string, timestamp: string): string {
  const year = new Date(timestamp).getFullYear() || 2026;
  const suffix = scanId.replace(/-/g, '').slice(0, 6).toUpperCase();
  return `SGR-${year}-${suffix}`;
}

// Generate forensic report data
reportsRouter.get('/:id', (req: Request, res: Response) => {
  const db = getDatabase();
  const scanId = req.params.id;
  const userId = req.user?.id;
  const isAdmin = req.user?.role === 'admin';

  const stmt = db.prepare('SELECT * FROM scans WHERE id = ?');
  const scan = stmt.get(scanId) as any;

  if (!scan) {
    res.status(404).json({ success: false, error: 'Scan record not found for report generation.' });
    return;
  }

  if (scan.user_id !== 'guest-analyst' && scan.user_id !== userId && !isAdmin) {
    res.status(403).json({ success: false, error: 'Access denied to this report.' });
    return;
  }

  const reportId = generateReportId(scan.id, scan.created_at);
  const indicators = JSON.parse(scan.indicators_json || '[]');
  const recommendations = JSON.parse(scan.recommendations_json || '[]');

  const classification = scan.prediction === 'scam' ? 'SCAM' : scan.prediction === 'suspicious' ? 'SUSPICIOUS' : 'SAFE';
  const riskLevel = scan.risk_score >= 80 ? 'CRITICAL' : scan.risk_score >= 60 ? 'HIGH' : scan.risk_score >= 30 ? 'MEDIUM' : 'LOW';

  const report = {
    reportId,
    scanId: scan.id,
    generatedAt: new Date().toISOString(),
    scanTimestamp: scan.created_at,
    scanType: scan.scan_type,
    platform: scan.platform || 'N/A',
    classification,
    prediction: scan.prediction,
    riskScore: scan.risk_score,
    riskLevel,
    confidence: scan.confidence,
    category: scan.category,
    intent: scan.prediction === 'scam' ? 'Social engineering / deceptive solicitation' : scan.prediction === 'suspicious' ? 'Ambiguous / unverified communication' : 'Harmless human communication',
    requestedAction: scan.prediction === 'scam' ? 'Direct request for credentials, fees, or urgent action' : 'None',
    requiresReview: scan.prediction === 'suspicious',
    analysisEngine: scan.engine === 'openai' ? 'OpenAI GPT Neural Threat Engine' : scan.engine === 'gemini' ? 'Google Gemini AI Threat Engine' : 'Offline Deterministic Security Rule Engine',
    inputSummary: scan.input_summary,
    inputRaw: scan.input_raw,
    indicators,
    explanation: scan.explanation,
    recommendations,
    disclaimer: 'DISCLAIMER: This document is an automated cybersecurity threat intelligence report generated by SCAMGUARD AI. It is intended for informational and advisory triage purposes and does not constitute a certified legal or judicial forensic declaration.',
    limitations: [
      'Analysis is performed on submitted textual & structural telemetry only.',
      'Offline heuristic fallback does not query external third-party threat feeds or active C2 infrastructure.',
      'Active network scanning and sandbox execution are omitted to protect server integrity and prevent SSRF attacks.',
    ],
  };

  const format = req.query.format;
  if (format === 'json') {
    res.setHeader('Content-Type', 'application/json');
    res.setHeader('Content-Disposition', `attachment; filename="${reportId}.json"`);
    res.send(JSON.stringify(report, null, 2));
    return;
  }

  if (format === 'txt') {
    const txtContent = `================================================================================
SCAMGUARD AI - FORENSIC THREAT INTELLIGENCE REPORT
================================================================================
REPORT ID      : ${report.reportId}
SCAN ID        : ${report.scanId}
GENERATED AT   : ${report.generatedAt}
ORIGINAL SCAN  : ${report.scanTimestamp}
SCAN TYPE      : ${report.scanType.toUpperCase()}
PLATFORM       : ${report.platform}
ENGINE USED    : ${report.analysisEngine}
--------------------------------------------------------------------------------
THREAT VERDICT
--------------------------------------------------------------------------------
CLASSIFICATION : ${report.classification} (${report.riskLevel} RISK)
RISK SCORE     : ${report.riskScore} / 100
CONFIDENCE     : ${(report.confidence * 100).toFixed(1)}%
CATEGORY       : ${report.category.toUpperCase()}

INPUT SUMMARY:
${report.inputSummary}

--------------------------------------------------------------------------------
FORENSIC EXPLANATION
--------------------------------------------------------------------------------
${report.explanation}

--------------------------------------------------------------------------------
IDENTIFIED THREAT INDICATORS
--------------------------------------------------------------------------------
${indicators.length > 0
  ? indicators.map((ind: any, i: number) => `[${i + 1}] Phrase: "${ind.phrase}"\n    Reason: ${ind.reason}`).join('\n\n')
  : 'None detected.'}

--------------------------------------------------------------------------------
SECURITY RECOMMENDATIONS
--------------------------------------------------------------------------------
${recommendations.map((rec: string, i: number) => `[${i + 1}] ${rec}`).join('\n')}

--------------------------------------------------------------------------------
VERIFICATION LIMITATIONS & DISCLAIMER
--------------------------------------------------------------------------------
${report.disclaimer}

LIMITATIONS:
${report.limitations.map(l => `- ${l}`).join('\n')}
================================================================================
END OF REPORT - SCAMGUARD AI SOC
================================================================================`;

    res.setHeader('Content-Type', 'text/plain; charset=utf-8');
    res.setHeader('Content-Disposition', `attachment; filename="${reportId}.txt"`);
    res.send(txtContent);
    return;
  }

  res.json({
    success: true,
    report,
  });
});
